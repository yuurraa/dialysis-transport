import { test, expect, seedSession, activeAccount, fixtureTrip, mockServices } from './support/fixtures';

test.beforeEach(mockServices);

test('mobile navigation traps focus, supports dismissal and opens protected pages', async ({ page }) => {
  await seedSession(page);
  await page.route('**/api/auth/me', route => route.fulfill({ json: { account: { ...activeAccount, role: 'coordinator' } } }));
  await page.route('**/api/trips/notifications?*',route=>route.fulfill({json:{notifications:[{id:'99999999-9999-4999-8999-999999999999',trip_id:fixtureTrip.id,message:'Driver assigned',event:'assigned',created_at:'2026-10-26T02:00:00Z',read_at:null}],unread:1,total:1,page:1,pageSize:10}}));
  await page.goto('/dashboard');
  await expect(page.getByRole('button',{name:'Notifications',exact:true})).toHaveAttribute('aria-expanded','false');
  await expect(page.getByLabel('1 unread notifications',{exact:true})).toBeVisible();
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  const width = 375;

  await page.setViewportSize({ width, height: 900 });
  const toggle = page.locator('.dashboard-menu-toggle');
  const drawer = page.getByRole('dialog', { name: 'Menu navigation' });
  await expect(toggle).toHaveAttribute('aria-expanded', 'false');
  await expect(page.locator('.dashboard-header .dashboard-brand')).toBeHidden();
  await toggle.click();
  await expect(drawer).toBeVisible();

  await expect(drawer.getByRole('button', { name: 'Close navigation' })).toBeFocused();
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden');
  await page.keyboard.press('Tab');
  await expect(drawer.getByRole('link', { name: 'Trips', exact: true })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(drawer.getByRole('link', { name: 'Schedules', exact: true })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(drawer.getByRole('link', { name: 'Patients', exact: true })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(drawer.getByRole('link', { name: 'Caregivers', exact: true })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(drawer.getByRole('link', { name: 'Drivers', exact: true })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(drawer.getByRole('button', { name: 'Close navigation' })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(drawer).toBeHidden();
  await expect(toggle).toBeFocused();
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('');
  await toggle.click();
  await page.mouse.click(width - 4, 300);
  await expect(drawer).toBeHidden();
  await toggle.click();
  await drawer.getByRole('button', { name: 'Close navigation' }).click();
  await expect(drawer).toBeHidden();
  await toggle.click();
  await drawer.getByRole('link', { name: 'Trips', exact: true }).click();
  await expect(drawer).toBeHidden();
  await expect(toggle).toBeFocused();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await toggle.click();
  await expect(drawer).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(drawer).toBeHidden();
  await expect(toggle).toBeFocused();
  await page.getByRole('button',{name:'Account',exact:true}).click();
  await expect(page.getByRole('button',{name:'Demo Tools',exact:true})).toHaveCount(0);
  const coordinator={...activeAccount,role:'coordinator',demo_admin:true};
  const actor={...activeAccount,id:'dddddddd-dddd-4ddd-8ddd-dddddddddddd',auth_user_id:'dddddddd-dddd-4ddd-8ddd-dddddddddddd',role:'patient',display_name:'Tan Wee Kiat',demo_owner_id:null,demo_access_owner_id:activeAccount.id,seed_key:'patient1'};
  const demoState={actors:[actor],scenario:{trip_id:fixtureTrip.id,traffic:'normal',progress:0},trip:{...fixtureTrip,lifecycle:'scheduled',assigned_driver_id:null}};
  await page.route('**/api/auth/me',route=>route.fulfill({json:{account:coordinator}}));
  await page.route('**/api/demo',route=>route.fulfill({json:demoState}));
  await page.route('**/api/demo/switch',route=>route.fulfill({json:{access_token:'demo-patient-token',expires_at:4102444800,account:actor}}));
  const tripTokens:string[]=[];
  await page.route('**/api/trips?*',route=>{tripTokens.push(route.request().headers().authorization??'');return route.fulfill({json:{trips:[],total:0,page:1,pageSize:25,counts:{},next_trip:null}});});
  await page.reload();
  await page.getByRole('button',{name:'Account',exact:true}).click();
  await page.getByRole('button',{name:'Demo Tools',exact:true}).click();
  const tools=page.getByRole('dialog',{name:'Demo Tools',exact:true});
  await expect(tools).toBeVisible();
  await tools.getByLabel('View as',{exact:true}).selectOption(actor.id);
  const strip=page.getByRole('complementary',{name:'Demo session',exact:true});
  await expect(strip).toContainText('Tan Wee Kiat');
  await expect.poll(()=>tripTokens.includes('Bearer demo-patient-token')).toBe(true);
  const main=page.locator('.dashboard-main');
  const gap=await main.evaluate(element=>getComputedStyle(element).paddingTop);
  await strip.getByRole('button',{name:'Controls',exact:true}).click();
  await expect(tools).toBeVisible();
  expect(await main.evaluate(element=>getComputedStyle(element).paddingTop)).toBe(gap);
  await tools.getByRole('button',{name:'Close',exact:true}).click();
  await expect(tools).toHaveCount(0);
  expect(await main.evaluate(element=>getComputedStyle(element).paddingTop)).toBe(gap);
  await strip.getByRole('button',{name:'Return',exact:true}).click();
  await expect(strip).toHaveCount(0);
  await expect.poll(()=>tripTokens.at(-1)).toBe('Bearer fixture-access-token');
  await page.reload();
  await expect(strip).toHaveCount(0);
});
