test('coordinator calendar separates dated bookings from repeated availability across four weeks', async ({ page }) => {
  await seedSession(page);
  await page.setViewportSize({width:1280,height:900});
  const driverId='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
  const local=new Date(Date.now()+8*3600000);const today=local.toISOString().slice(0,10);
  const mondayDate=new Date(`${today}T00:00:00Z`);mondayDate.setUTCDate(mondayDate.getUTCDate()+1-(mondayDate.getUTCDay()||7));
  const monday=mondayDate.toISOString().slice(0,10);
  const trip={id:'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb',patient_name:'Calendar Patient',direction:'outbound',pickup_at:`${monday}T09:15:00+08:00`,dropoff_at:`${monday}T09:45:00+08:00`,origin:'Fixture home',destination:'Fixture centre',status:'on-track'};
  const second={...trip,id:'cccccccc-cccc-4ccc-8ccc-cccccccccccc',patient_name:'Second Patient',pickup_at:`${monday}T09:45:00+08:00`,dropoff_at:`${monday}T10:15:00+08:00`};
  let assigned=true;let requested='';let holdNext:Promise<void>|null=null;let resumeNext:(()=>void)|undefined;
  await page.route('**/api/auth/me',route=>route.fulfill({json:{account:{...activeAccount,role:'coordinator'}}}));
  await page.route('**/api/drivers?*',route=>route.fulfill({json:{drivers:[{id:driverId,email:'driver@example.test',display_name:'Calendar Driver',account_status:'active',status_version:1,profile:{full_name:'Calendar Driver',phone:'81234567',birth_date:'1990-01-01',gender:'male'},vehicle:{status:'approved',plate_number:'TEST123'}}],total:1,page:1,pageSize:25,counts:{approved:1}}}));
  await page.route('**/api/drivers/*/week?*',async route=>{requested=new URL(route.request().url()).searchParams.get('start')!;if(holdNext&&requested!==monday){const pending=holdNext;holdNext=null;await pending;}return route.fulfill({json:{eligible:true,availability:{weekly_slots:[18,19,20,66,67],version:1},trips:assigned&&requested===monday?[trip,second]:[]}});});
  await page.goto('/dashboard/drivers');
  await page.getByRole('button',{name:/View.*availability|View.*schedule/i}).click();
  const dialog=page.getByRole('dialog',{name:'Driver calendar',exact:true});
  await expect(dialog.getByRole('button',{name:'Previous week',exact:true})).toBeDisabled();
  await expect(dialog.locator('.availability-booked')).toHaveCount(3);
  await dialog.locator('.availability-booked').filter({hasText:'2 trips'}).click();
  await expect(page.getByRole('dialog',{name:'Assigned trips',exact:true})).toContainText('Second Patient');
  await expect(page.locator('dialog[open]')).toHaveCount(2);
  await page.getByRole('dialog',{name:'Assigned trips',exact:true}).getByRole('button',{name:/Calendar Patient · Outbound/}).click();
  await expect(page.getByRole('dialog',{name:'Assigned trip',exact:true})).toContainText('Calendar Patient');
  await expect(page.locator('dialog[open]')).toHaveCount(3);
  await page.getByRole('button',{name:'Close Assigned trip',exact:true}).click();
  await expect(page.locator('dialog[open]')).toHaveCount(2);
  await page.getByRole('button',{name:'Close Assigned trips',exact:true}).click();
  await expect(page.locator('dialog[open]')).toHaveCount(1);
  holdNext=new Promise<void>(resolve=>{resumeNext=resolve;});
  await dialog.getByRole('button',{name:'Next week',exact:true}).click();
  await expect(dialog.locator('.driver-calendar-viewport')).toHaveAttribute('aria-busy','true');
  await expect(dialog.locator('.availability-booked')).toHaveCount(3);
  await expect(dialog.getByText('Loading...', {exact:true})).toHaveCount(0);
  resumeNext!();
  await expect(dialog.locator('.availability-booked')).toHaveCount(0);
  await expect(dialog.locator('.availability-slot[aria-pressed=true]')).toHaveCount(5);
  await dialog.getByRole('button',{name:'Next week',exact:true}).click();await dialog.getByRole('button',{name:'Next week',exact:true}).click();
  await expect(dialog.getByRole('button',{name:'Next week',exact:true})).toBeDisabled();
  assigned=false;
  for(let index=0;index<3;index++) await dialog.getByRole('button',{name:'Previous week',exact:true}).click();
  await expect.poll(()=>requested).toBe(monday);
  await expect(dialog.locator('.availability-booked')).toHaveCount(0);
  await expect(dialog.locator('.availability-slot[aria-pressed=true]')).toHaveCount(5);
});
